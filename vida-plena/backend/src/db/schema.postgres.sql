-- Banco de produção (PostgreSQL). Aplicado na subida do servidor; pode rodar várias vezes.
-- Valores em dinheiro: NUMERIC(12,2). Datas da apólice: DATE. Momentos: TIMESTAMPTZ (UTC).

CREATE TABLE IF NOT EXISTS clientes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cpf TEXT NOT NULL UNIQUE,
  nome TEXT NOT NULL,
  email TEXT NOT NULL,
  telefone TEXT,
  nascimento DATE NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS cotacoes (
  id TEXT PRIMARY KEY,                    -- id devolvido pela seguradora
  entrada_json TEXT NOT NULL,             -- dados e coberturas pedidos
  resposta_json TEXT NOT NULL,            -- resposta completa da seguradora
  premio_liquido NUMERIC(12,2) NOT NULL,
  iof NUMERIC(12,2) NOT NULL,
  premio_mensal NUMERIC(12,2) NOT NULL,
  premio_anual NUMERIC(12,2) NOT NULL,
  valida_ate DATE NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS propostas (
  numero TEXT PRIMARY KEY,
  cotacao_id TEXT NOT NULL REFERENCES cotacoes(id),
  cliente_id INTEGER NOT NULL REFERENCES clientes(id),
  beneficiarios TEXT NOT NULL,
  declaracao_saude_json TEXT NOT NULL,    -- dado sensível (LGPD): gravado criptografado (AES-256-GCM)
  periodicidade TEXT NOT NULL CHECK (periodicidade IN ('mensal','anual')),
  status TEXT NOT NULL,                   -- ACEITA, EM_ANALISE_SUBSCRICAO, RECUSADA, APOLICE_EMITIDA, CANCELADA
  numero_apolice TEXT,
  comissao_percentual NUMERIC(5,2) NOT NULL, -- guardado por proposta: mudar a config não altera o histórico
  aceites_json TEXT NOT NULL,
  aceites_ip TEXT,
  vigencia_inicio DATE,
  vigencia_fim DATE,
  renovacao_automatica SMALLINT NOT NULL DEFAULT 1 CHECK (renovacao_automatica IN (0,1)),
  renovacoes INTEGER NOT NULL DEFAULT 0,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS pagamentos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proposta_numero TEXT NOT NULL REFERENCES propostas(numero),
  valor NUMERIC(12,2) NOT NULL,           -- valor cobrado (com IOF)
  premio_liquido NUMERIC(12,2) NOT NULL,  -- parte sem IOF, base da comissão
  parcelas INTEGER NOT NULL,
  recorrente SMALLINT NOT NULL CHECK (recorrente IN (0,1)),
  status TEXT NOT NULL,                   -- APROVADO, RECUSADO, ESTORNADO
  autorizacao TEXT,
  cartao_final TEXT,
  cartao_bandeira TEXT,
  motivo TEXT,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS comissoes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proposta_numero TEXT NOT NULL REFERENCES propostas(numero),
  pagamento_id INTEGER NOT NULL UNIQUE REFERENCES pagamentos(id),
  base_calculo NUMERIC(12,2) NOT NULL,    -- prêmio líquido do pagamento
  percentual NUMERIC(5,2) NOT NULL,
  valor NUMERIC(12,2) NOT NULL,
  status TEXT NOT NULL,                   -- PREVISTA, A_RECEBER, RECEBIDA, CANCELADA
  recebida_em TIMESTAMPTZ,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS renovacoes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proposta_numero TEXT NOT NULL REFERENCES propostas(numero),
  vigencia_anterior_fim DATE NOT NULL,
  nova_vigencia_inicio DATE NOT NULL,
  nova_vigencia_fim DATE NOT NULL,
  status TEXT NOT NULL,                   -- RENOVADA, NAO_RENOVADA
  motivo TEXT,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_comissoes_status ON comissoes(status);
CREATE INDEX IF NOT EXISTS idx_comissoes_proposta ON comissoes(proposta_numero);
CREATE INDEX IF NOT EXISTS idx_propostas_status ON propostas(status);
CREATE INDEX IF NOT EXISTS idx_propostas_vigencia ON propostas(vigencia_fim);
CREATE INDEX IF NOT EXISTS idx_pagamentos_proposta ON pagamentos(proposta_numero);
CREATE INDEX IF NOT EXISTS idx_pagamentos_autorizacao ON pagamentos(autorizacao);
